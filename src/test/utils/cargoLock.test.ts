describe("[replace]の解決(レビュー指摘: 置換元のcrates.ioのcrateをスキャンしない)", () => {
  const fanIn = (count: number): string => Array.from({ length: count - 1 }, (_, i) =>
    `[[package]]\nname = "crate-${i}"\nversion = "1.0.0"\nsource = "${CRATES_IO}"\nreplace = "target 1.0.0"\n`,
  ).join("\n") + '\n[[package]]\nname = "target"\nversion = "1.0.0"\n';

  it("does not rescan package arrays for every replacement", () => {
    const text = fanIn(1000);
    const scan = vi.spyOn(Array.prototype, "some");
    let rescans: number;
    try {
      const parsed = parseCargoLock(text);
      expect(parsed.ok).toBe(true);
      rescans = scan.mock.contexts.filter((value) => Array.isArray(value) && value.length === 1000).length;
    } finally {
      scan.mockRestore();
    }
    expect(rescans).toBeLessThanOrEqual(1);
  });

  it("handles the package limit with replacements all pointing to the final package", () => {
    const parsed = parseCargoLock(fanIn(50_000));
    if (!parsed.ok) throw new Error(parsed.reason);
    expect(parsed.packages).toHaveLength(50_000);
    expect(parsed.packages[0]!.replace).toBe("target 1.0.0");
    const classified = classifyCargoPackages(parsed.packages);
    expect(classified.cratesIo).toEqual([]);
    expect(classified.localCrates).toEqual(["target"]);
    expect(parseCargoLock(fanIn(50_001))).toMatchObject({ ok: false, reason: expect.stringContaining("more than 50000 packages") });
  });

  it("preserves a distinct duplicate identity while rejecting a singleton self-reference", () => {
    const block = '[[package]]\nname = "a"\nversion = "1"\nreplace = "a 1"\n';
    expect(parseCargoLock(block)).toMatchObject({ ok: false });
    const parsed = parseCargoLock(block + '\n[[package]]\nname = "a"\nversion = "1"\n');
    expect(parsed.ok && parsed.packages).toHaveLength(2);
    expect(parseCargoLock(block + "\n" + block).ok).toBe(true);
  });

  it("keeps the first replacement failure and never returns partial packages", () => {
    const parsed = parseCargoLock(
      '[[package]]\nname = "first"\nversion = "1"\nreplace = "missing 1"\n' +
      '\n[[package]]\nname = "second"\nversion = "1"\nreplace = "also-missing 1"\n',
    );
    expect(parsed).toEqual({ ok: false, reason: expect.stringContaining("the replacement of first 1") });
  });

  it.each([
    ["different name", "target", "1", null, "other 1"],
    ["different version", "target", "1", null, "target 2"],
    ["source omitted", "target", "1", CRATES_IO, "target 1"],
    ["empty source", "target", "1", "", "target 1"],
    ["registry versus sparse", "target", "1", CRATES_IO, `target 1 (${SPARSE})`],
    ["hyphen versus underscore", "a-b", "1", null, "a_b 1"],
  ] as const)("matches replacement identity exactly: %s", (_label, name, version, source, replacement) => {
    const text = `[[package]]\nname = "original"\nversion = "1"\nreplace = "${replacement}"\n` +
      `\n[[package]]\nname = "${name}"\nversion = "${version}"\n${source === null ? "" : `source = "${source}"\n`}`;
    expect(parseCargoLock(text)).toMatchObject({ ok: false, reason: expect.stringContaining("the replacement of original 1") });
  });

  it("preserves immediate-target validation for forward references, chains, and cycles", () => {
    const parsed = parseCargoLock(
      '[[package]]\nname = "a"\nversion = "1"\nreplace = "b 1"\n' +
      '\n[[package]]\nname = "b"\nversion = "1"\nreplace = "c 1"\n' +
      '\n[[package]]\nname = "c"\nversion = "1"\nreplace = "a 1"\n',
    );
    expect(parsed.ok && parsed.packages.map((p) => p.name)).toEqual(["a", "b", "c"]);
  });

  /** cargo 1.98(generate-lockfile --offline)が`[replace] "anyhow:1.0.102" = { path = "fake" }`で生成した内容 */
  const REPLACED_BY_PATH = `version = 4

[[package]]
name = "adler2"
version = "2.0.1"
source = "${CRATES_IO}"
checksum = "320119579fcad9c21884f5c4861d16174d0e06250625266f50fe6898340abefa"

[[package]]
name = "anyhow"
version = "1.0.102"

[[package]]
name = "anyhow"
version = "1.0.102"
source = "${CRATES_IO}"
checksum = "7f202df86484c868dbad7eaa557ef785d5c66295e41b460ef922eca0723b842c"
replace = "anyhow 1.0.102"

[[package]]
name = "rep"
version = "0.1.0"
dependencies = [
 "adler2",
 "anyhow 1.0.102 (${CRATES_IO})",
]
`;

  it("pathへの置換: 置換元(crates.io)はスキャンせず、置換先はローカルのcrateとして数える", () => {
    const parsed = parseCargoLock(REPLACED_BY_PATH);
    if (!parsed.ok) throw new Error(parsed.reason);
    expect(parsed.packages[2]!.replace).toBe("anyhow 1.0.102");
    const classified = classifyCargoPackages(parsed.packages);
    expect(classified.cratesIo.map((p) => p.name)).toEqual(["adler2"]);
    expect(classified.localCrates).toEqual(["anyhow", "rep"]);
    expect(cargoLockCopyContent(classified.cratesIo)).not.toContain("anyhow");
  });

  it("gitへの置換: 置換先はgitの依存としてスキャンしない", () => {
    const git = "git+https://github.com/me/anyhow?branch=fix#0123456789abcdef";
    const text = `version = 4

[[package]]
name = "anyhow"
version = "1.0.102"
source = "${CRATES_IO}"
replace = "anyhow 1.0.102 (${git})"

[[package]]
name = "anyhow"
version = "1.0.102"
source = "${git}"
`;
    const parsed = parseCargoLock(text);
    if (!parsed.ok) throw new Error(parsed.reason);
    const classified = classifyCargoPackages(parsed.packages);
    expect(classified.cratesIo).toEqual([]);
    expect(classified.unscannable).toEqual([{ name: "anyhow", version: "1.0.102", kind: "git" }]);
  });

  it.each([
    ["置換先の記載が無い", `replace = "anyhow 1.0.102 (git+https://x#abc)"`],
    ["置換先のIDを解釈できない", `replace = "anyhow"`],
    ["自分自身を指す", `replace = "anyhow 1.0.102 (${CRATES_IO})"`],
  ])("置換先を確かめられなければファイル全体を除外する(%s)", (_label, replaceLine) => {
    const result = parseCargoLock(`[[package]]\nname = "anyhow"\nversion = "1.0.102"\nsource = "${CRATES_IO}"\n${replaceLine}\n`);
    expect(result).toEqual({ ok: false, reason: expect.stringContaining("the replacement of anyhow 1.0.102 by [replace] was not found") });
  });

  it("parsePackageId", () => {
    expect(parsePackageId("a 1.0.0")).toEqual({ name: "a", version: "1.0.0", source: null });
    expect(parsePackageId(`a 1.0.0 (${CRATES_IO})`)).toEqual({ name: "a", version: "1.0.0", source: CRATES_IO });
    expect(parsePackageId("a")).toBeNull();
  });
});

describe("cargoWorkspace / workspaceIncludes(レビュー指摘: 名前だけで所属を確定しない)", () => {
  /** cargo 1.98で確認したworkspace: lockfileに収録されたのはca・cb・cinner・tt1(crates/exは除外、otherは非メンバー) */
  const ROOT = `[workspace]
members = [
  "crates/*", # glob
  "./crates/ex/inner/",
  "tools/t?",
]
exclude = ["crates/ex"]
resolver = "2"
`;

  it("membersとexcludeを複数行・コメント・末尾カンマ付きで読む", () => {
    expect(cargoWorkspace(ROOT)).toEqual({ members: ["crates/*", "./crates/ex/inner/", "tools/t?"], exclude: ["crates/ex"] });
  });

  it.each([
    ["crates/a", true],
    ["crates/b", true],
    ["crates/ex", false], // globで一致してもexcludeで除かれる
    ["crates/ex/inner", true], // 文字どおり書かれたメンバーはexcludeより優先
    ["tools/t1", true],
    ["tools/t10", false],
    ["other", false],
    ["crates/a/nested", false],
  ])("cargoの実際の挙動と同じ判定: %s → %s", (dir, expected) => {
    expect(workspaceIncludes(cargoWorkspace(ROOT)!, dir)).toBe(expected);
  });

  it.each([
    ["**のglob", { members: ["crates/**"], exclude: [] }, "crates/a"],
    ["文字クラスのglob", { members: ["crates/[ab]"], exclude: [] }, "crates/a"],
    ["ルートの外を指すメンバー", { members: ["../x"], exclude: [] }, "crates/a"],
    ["解釈できないexclude", { members: ["crates/*"], exclude: ["/abs"] }, "crates/a"],
  ])("判定できない場合はnull(%s)", (_label, workspace, dir) => {
    expect(workspaceIncludes(workspace, dir)).toBeNull();
  });

  it.each([
    ["[workspace]が無い", `[package]\nname = "app"\n`],
    ["membersが文字列の配列でない", `[workspace]\nmembers = ['a']\n`],
    ["閉じない配列", `[workspace]\nmembers = ["a",\n`],
  ])("cargoWorkspaceはnull(%s)", (_label, text) => {
    expect(cargoWorkspace(text)).toBeNull();
  });
});

describe("workspaceIncludes: bounded glob matching", () => {
  it("returns unknown when a single glob exceeds the work budget", () => {
    expect(workspaceIncludes({ members: ["?".repeat(1100)], exclude: [] }, "a".repeat(1100))).toBeNull();
    expect(workspaceIncludes({ members: ["*a".repeat(10_000) + "b"], exclude: [] }, "a".repeat(64))).toBeNull();
  });

  it("shares the work budget across member patterns", () => {
    const pattern = "*" + "?".repeat(98) + "b";
    const target = "a".repeat(99);
    expect(workspaceIncludes({ members: [pattern], exclude: [] }, target)).toBe(false);
    expect(workspaceIncludes({ members: Array<string>(100).fill(pattern), exclude: [] }, target)).toBeNull();
  });

  it.each([
    ["*a".repeat(32) + "b", "a".repeat(64), false],
    ["a*".repeat(32) + "?b", "a".repeat(64), false],
    ["*a".repeat(32) + "b", "a".repeat(64) + "b", true],
    ["a*b?c", "abxc", true],
    ["a*b?c", "axyzbxc", true],
    ["a*b?c", "abc", false],
    ["crates/*", "crates/a/nested", false],
    ["crates/a.+(x)$^|", "crates/a.+(x)$^|", true],
    ["crates/a.+(x)$^|", "crates/ax", false],
    ["./crates\\t?/", "crates/t1", true],
    ["*?", "\n", true],
    ["?", "\u{1f600}", false],
    ["??", "\u{1f600}", true],
    ["a", "a\n", false],
  ])("matches %s against %s without backtracking", (pattern, target, expected) => {
    expect(workspaceIncludes({ members: [pattern], exclude: [] }, target)).toBe(expected);
  });

  it("keeps a confirmed member when another pattern exceeds the budget", () => {
    const target = "a".repeat(1100);
    expect(workspaceIncludes({ members: [target, "?".repeat(1100)], exclude: [] }, target)).toBe(true);
  });

  it("keeps unsupported syntax unknown even when path depths differ", () => {
    expect(workspaceIncludes({ members: ["crates/**/nested"], exclude: [] }, "other")).toBeNull();
  });
});

describe("Cargo.tomlの複数行文字列(レビュー指摘: 文字列内の記述を設定と誤認しない)", () => {
  /** レビューで示された例: 説明文の中にworkspaceの設定に見える記述がある有効なCargo.toml */
  const DESCRIPTION_LOOKS_LIKE_WORKSPACE = `[package]
name = "app"
version = "0.1.0"
description = """
[workspace]
members = ["sub"]
"""
`;

  it.each([
    ["レビューの例", DESCRIPTION_LOOKS_LIKE_WORKSPACE],
    // 閉じの引用符がmembersの行末にあり、行ごとの判定では引用符で始まる行が現れない形
    ["閉じの引用符が同じ行にある", `[package]\nname = "app"\ndescription = """\n[workspace]\nmembers = ["sub"]"""\n`],
  ])("複数行の基本文字列の中の[workspace]はworkspaceとみなさない(%s)", (_label, text) => {
    expect(cargoWorkspace(text)).toBeNull();
    expect(cargoTomlPackageName(text)).toBe("app");
  });

  it("複数行のリテラル文字列の中の[package]・nameは読まない", () => {
    const text = `[workspace.metadata]\ndoc = \'\'\'\n[package]\nname = "fake"\n\'\'\'\n\n[package]\nname = "real"\n`;
    expect(cargoTomlPackageName(text)).toBe("real");
  });

  it("文字列の後に本物のworkspaceがあれば読む(閉じの引用符の直前の引用符・文字列内の括弧・#を含む)", () => {
    const text = `[package]
name = "app"
description = """x [workspace] ""\\""""
readme = "a ] # b"
license = 'MIT # [x]'

[workspace]
members = ["crates/*"] # c
`;
    expect(cargoWorkspace(text)).toEqual({ members: ["crates/*"], exclude: [] });
    expect(cargoTomlPackageName(text)).toBe("app");
  });

  it("複数行の配列の中の見出しに見える行も見出しとみなさない", () => {
    const text = `[workspace]\nmembers = [\n  "a",\n]\nexclude = [\n  "b",\n]\n`;
    expect(cargoWorkspace(text)).toEqual({ members: ["a"], exclude: ["b"] });
    expect(topLevelTomlLines(`a = [\n"[workspace]",\n]\n`)!.map((l) => l.line)).toEqual(["a = [", ""]);
  });

  it.each([
    ["閉じない複数行文字列", `[package]\nname = "app"\ndescription = """\n[workspace]\nmembers = ["sub"]\n`],
    ["閉じない文字列", `[package]\nname = "app\n[workspace]\nmembers = ["sub"]\n`],
    ["括弧の不整合", `[workspace]\nmembers = ["a"]]\n`],
  ])("解釈できない場合はnull(%s)", (_label, text) => {
    expect(topLevelTomlLines(text)).toBeNull();
    expect(cargoWorkspace(text)).toBeNull();
    expect(cargoTomlPackageName(text)).toBeNull();
  });

  it.each([
    ["引用符付きのキー", `[workspace]\nmembers = ["*"]\n"exclude" = ["sub"]\n`],
    ["ルートのテーブルのドット付きのキー", `workspace.exclude = ["sub"]\n[workspace]\nmembers = ["*"]\n`],
    ["配列の中の複数行文字列", `[workspace]\nmembers = ["""a"""]\n`],
  ])("読み落としの可能性がある書き方はnull(%s)", (_label, text) => {
    expect(cargoWorkspace(text)).toBeNull();
  });
});

describe("workspaceIncludes: 検出全体で共有する計算量の上限(レビュー指摘)", () => {
  const heavy = { members: ["*/" + "*a".repeat(1900) + "*b"], exclude: [] };
  const member = (i: number) => `m${i}/${"a".repeat(250)}`;

  it.each([1, 7, 38])("exhausts an unusable positive residual budget (%i)", (remaining) => {
    const workspace = { members: ["*a*a*a*b", "*a*a*a*c", "*a*a*a*d"], exclude: [] };
    const total = createGlobWorkBudget(remaining);
    expect(workspaceIncludes(workspace, "a".repeat(30), total)).toBeNull();
    expect(total.remaining).toBe(0);
    expect(workspaceIncludes(workspace, "a".repeat(30), total)).toBeNull();
    expect(total.remaining).toBe(0);
  });

  it("exhausts the default shared budget naturally without retaining a positive remainder", () => {
    const workspace = { members: Array<string>(5000).fill("*a*a*a*b"), exclude: [] };
    const total = createGlobWorkBudget();
    for (let i = 0; i < 20; i++) expect(workspaceIncludes(workspace, "a".repeat(30), total)).toBeNull();
    expect(total.remaining).toBe(0);
  });

  it("still considers a cheaper matching glob when only the DP reservation fails", () => {
    const workspace = { members: ["?".repeat(1100), "*"], exclude: [] };
    const total = createGlobWorkBudget();
    expect(workspaceIncludes(workspace, "a".repeat(1100), total)).toBe(true);
    expect(total.remaining).toBeGreaterThan(0);
  });

  it("charges only the per-member allowance when a larger shared budget remains", () => {
    const workspace = { members: Array<string>(1000).fill("*" + "?".repeat(510) + "b"), exclude: [] };
    const total = createGlobWorkBudget(3_000_000);
    expect(workspaceIncludes(workspace, "a".repeat(511), total)).toBeNull();
    expect(total.remaining).toBe(2_000_000);
    expect(workspaceIncludes({ members: ["*"], exclude: [] }, "a", total)).toBe(true);
    expect(total.remaining).toBeGreaterThan(0);
  });

  it("accepts exact-cost matches and continues after unsupported syntax", () => {
    const total = createGlobWorkBudget(7);
    expect(workspaceIncludes({ members: ["?"], exclude: [] }, "a", total)).toBe(true);
    expect(total.remaining).toBe(0);
    expect(workspaceIncludes({ members: ["**", "*"], exclude: [] }, "a", createGlobWorkBudget(100))).toBe(true);
  });

  it("回帰: 共有の上限を渡すと、メンバーごとに上限が戻らず、使い切った後は未確認(null)になる", () => {
    const total = createGlobWorkBudget(3_000_000);
    const results = Array.from({ length: 6 }, (_, i) => workspaceIncludes(heavy, member(i), total));
    // 1回あたり約0.95Mセル: 3回は照合して不一致(false)、使い切った後は判定しない
    expect(results).toEqual([false, false, false, null, null, null]);
    expect(total.remaining).toBeLessThan(1_000_000);
    // 共有の上限を渡さない呼び出しは、従来どおり1回ごとの上限だけ
    expect(workspaceIncludes(heavy, member(9))).toBe(false);
  });

  it("文字どおりのメンバーは共有の上限を使わず、使い切った後も確認できる", () => {
    const total = createGlobWorkBudget(0);
    const workspace = { members: ["crates/a", "crates/b*"], exclude: ["crates/a/x"] };
    expect(workspaceIncludes(workspace, "crates/a", total)).toBe(true);
    expect(workspaceIncludes(workspace, "crates/bb", total)).toBeNull(); // globは上限切れで判定しない
    expect(total.remaining).toBe(0);
  });

  it.each([0, 1, 23])("上限を使い切ったら残りのglobを見ない(初期残額=%i)", (remaining) => {
    const workspace = { members: Array.from({ length: 100_000 }, (_, i) => `zz${i}*`), exclude: [] };
    const total = createGlobWorkBudget(remaining);
    const started = performance.now();
    // 空回りする実装では10,000回×100,000パターン(10億回)になり、この上限を大きく超える
    for (let i = 0; i < 10_000; i++) expect(workspaceIncludes(workspace, `m${i}`, total)).toBeNull();
    expect(performance.now() - started).toBeLessThan(1_000);
  });

  it("文字どおりのメンバーの前方一致(excludeより優先)とexcludeは、globを含む文字列も従来どおり扱う", () => {
    const workspace = { members: ["crates/*", "crates/ex/inner"], exclude: ["crates/ex"] };
    expect(workspaceIncludes(workspace, "crates/ex")).toBe(false);
    expect(workspaceIncludes(workspace, "crates/ex/inner")).toBe(true);
    expect(workspaceIncludes({ members: ["*"], exclude: ["*"] }, "*")).toBe(true); // 名前が"*"のディレクトリ(Cargoは文字列のまま前方一致を見る)
  });
});
