import { describe, expect, it } from "vitest";
import {
  cargoLockCopyContent,
  cargoSourceKind,
  cargoTomlPackageName,
  cargoWorkspace,
  classifyCargoPackages,
  parseCargoLock,
  parsePackageId,
  topLevelTomlLines,
  workspaceIncludes,
} from "../../utils/cargoLock.js";

const CRATES_IO = "registry+https://github.com/rust-lang/crates.io-index";
const SPARSE = "sparse+https://index.crates.io/";

/** 2026-10-11の実機確認に使ったworkspace(v3形式)を縮約したもの */
const V3 = `# This file is automatically @generated by Cargo.
# It is not intended for manual editing.
version = 3

[[package]]
name = "app"
version = "0.1.0"
dependencies = [
 "failure",
 "mylib",
 "smallvec 1.6.0",
]

[[package]]
name = "failure"
version = "0.1.8"
source = "${CRATES_IO}"
checksum = "d32e9bd16cc02eae7db7ef620b392808b89f6a5e16bb3497d159c6b92a0f4f86"
dependencies = [
 "smallvec 0.6.9",
]

[[package]]
name = "gitdep"
version = "0.3.0"
source = "git+https://github.com/example/gitdep#0123456789abcdef0123456789abcdef01234567"

[[package]]
name = "mylib"
version = "0.2.0"
dependencies = [
 "gitdep",
]

[[package]]
name = "private"
version = "1.0.0"
source = "registry+https://my-company.example/index"

[[package]]
name = "smallvec"
version = "0.6.9"
source = "${CRATES_IO}"

[[package]]
name = "smallvec"
version = "1.6.0"
source = "${SPARSE}"

[[patch.unused]]
name = "libc"
version = "0.2.80"
source = "${CRATES_IO}"
`;

describe("parseCargoLock", () => {
  it("v3形式: パッケージのname・version・source・依存を読み、[[patch.unused]]は無視する", () => {
    const result = parseCargoLock(V3);
    expect(result.ok).toBe(true);
    if (!result.ok) return;
    expect(result.packages.map((p) => `${p.name}@${p.version}`)).toEqual([
      "app@0.1.0", "failure@0.1.8", "gitdep@0.3.0", "mylib@0.2.0", "private@1.0.0", "smallvec@0.6.9", "smallvec@1.6.0",
    ]);
    expect(result.packages[0]).toEqual({ name: "app", version: "0.1.0", source: null, dependencies: ["failure", "mylib", "smallvec 1.6.0"] });
    expect(result.packages[1]!.source).toBe(CRATES_IO);
  });

  it("v4形式・CRLF・BOM・1行の依存配列・末尾のコメントを読む", () => {
    const text = `﻿version = 4\r\n\r\n[[package]] # c\r\nname = "a"\r\nversion = "1.0.0" # c\r\nsource = "${CRATES_IO}"\r\ndependencies = ["b", "c 1.0.0"]\r\n`;
    const result = parseCargoLock(text);
    expect(result).toEqual({ ok: true, packages: [{ name: "a", version: "1.0.0", source: CRATES_IO, dependencies: ["b", "c 1.0.0"] }] });
  });

  it("v1形式: 先頭のversionが無く、依存は`名前 版 (source)`、[metadata]のchecksumを読み飛ばす", () => {
    const text = `[[package]]
name = "app"
version = "0.1.0"
dependencies = [
 "smallvec 1.6.0 (${CRATES_IO})",
]

[[package]]
name = "smallvec"
version = "1.6.0"
source = "${CRATES_IO}"

[metadata]
"checksum smallvec 1.6.0 (${CRATES_IO})" = "1a55ca5f3b68e41c979bf8c46a6f1da892ca4db8f94023ce0bd32407573b1ac0"
`;
    const result = parseCargoLock(text);
    expect(result.ok && result.packages.map((p) => [p.name, p.dependencies])).toEqual([
      ["app", [`smallvec 1.6.0 (${CRATES_IO})`]],
      ["smallvec", []],
    ]);
  });

  it("文字列のエスケープを解釈する", () => {
    const result = parseCargoLock(`[[package]]\nname = "a\\u0062"\nversion = "1.0.0"\nsource = "x\\"y\\\\z"\n`);
    expect(result.ok && result.packages[0]).toEqual({ name: "ab", version: "1.0.0", source: 'x"y\\z', dependencies: [] });
  });

  it.each([
    ["想定外のテーブル", `[[package]]\nname = "a"\nversion = "1"\n[package.metadata]\n`],
    ["インラインテーブル", `[[package]]\nname = "a"\nversion = "1"\nsource = { git = "x" }\n`],
    ["リテラル文字列", `[[package]]\nname = 'a'\nversion = "1"\n`],
    ["複数行文字列", `[[package]]\nname = """a"""\nversion = "1"\n`],
    ["ドット付きのキー", `[[package]]\nname = "a"\nversion = "1"\nsource.git = "x"\n`],
    ["nameの重複", `[[package]]\nname = "a"\nname = "b"\nversion = "1"\n`],
    ["versionの欠落", `[[package]]\nname = "a"\n`],
    ["テーブルの後の先頭のversion", `[[package]]\nname = "a"\nversion = "1"\n[metadata]\nversion = 3\n`],
    ["先頭の他のキー", `foo = "x"\n[[package]]\nname = "a"\nversion = "1"\n`],
    ["閉じない依存配列", `[[package]]\nname = "a"\nversion = "1"\ndependencies = [\n "b",\n`],
    ["依存配列の想定外の要素", `[[package]]\nname = "a"\nversion = "1"\ndependencies = [\n b,\n]\n`],
    ["不正なエスケープ", `[[package]]\nname = "a\\q"\nversion = "1"\n`],
    ["サロゲートのエスケープ", `[[package]]\nname = "a\\uD800"\nversion = "1"\n`],
    ["値の後ろの余分な内容", `[[package]]\nname = "a" "b"\nversion = "1"\n`],
    ["crate名として不正な文字", `[[package]]\nname = "../x"\nversion = "1"\n`],
    ["版として不正な文字", `[[package]]\nname = "a"\nversion = "1 2"\n`],
    ["古い[root]テーブル", `[root]\nname = "a"\nversion = "1"\n`],
  ])("想定外の内容(%s)はファイル全体を失敗にし、行番号を示す", (_label, text) => {
    const result = parseCargoLock(text);
    expect(result.ok).toBe(false);
    if (!result.ok) expect(result.reason).toMatch(/^Cargo\.lock could not be interpreted with certainty \(.+ at line \d+\), so the file was excluded from the scan$/);
  });

  it("空のファイルはパッケージ0件", () => {
    expect(parseCargoLock("")).toEqual({ ok: true, packages: [] });
  });
});

describe("classifyCargoPackages", () => {
  it("crates.io由来だけをスキャン対象にし、ローカル・git・別レジストリを分ける", () => {
    const result = parseCargoLock(V3);
    if (!result.ok) throw new Error(result.reason);
    const classified = classifyCargoPackages(result.packages);
    expect(classified.cratesIo.map((p) => `${p.name}@${p.version}`)).toEqual(["failure@0.1.8", "smallvec@0.6.9", "smallvec@1.6.0"]);
    expect(classified.localCrates).toEqual(["app", "mylib"]);
    expect(classified.unscannable).toEqual([
      { name: "gitdep", version: "0.3.0", kind: "git" },
      { name: "private", version: "1.0.0", kind: "registry" },
    ]);
  });

  it("name・version・sourceが同じパッケージの重複は1つにまとめる", () => {
    const pkg = { name: "a", version: "1.0.0", source: CRATES_IO, dependencies: [] };
    expect(classifyCargoPackages([pkg, { ...pkg }]).cratesIo).toHaveLength(1);
  });

  it.each([
    [null, "local"],
    [CRATES_IO, "crates_io"],
    [SPARSE, "crates_io"],
    ["sparse+https://index.crates.io", "registry"], // 末尾の/が無いものはcrates.ioと断定しない
    ["registry+https://github.com/rust-lang/crates.io-index.git", "registry"],
    ["git+https://github.com/rust-lang/crates.io-index", "git"],
    ["path+file:///x", "registry"],
  ])("cargoSourceKind(%s) = %s", (source, kind) => {
    expect(cargoSourceKind(source)).toBe(kind);
  });
});

describe("cargoLockCopyContent", () => {
  it("crates.io由来のパッケージのname・version・sourceだけを書き、解析し直すと同じ内容になる", () => {
    const packages = [
      { name: "failure", version: "0.1.8", source: CRATES_IO, dependencies: ["smallvec 0.6.9"] },
      { name: "smallvec", version: "1.6.0-alpha.1+build", source: SPARSE, dependencies: [] },
    ];
    const content = cargoLockCopyContent(packages);
    expect(content).not.toContain("dependencies");
    expect(content.startsWith("version = 3\n")).toBe(true);
    expect(parseCargoLock(content)).toEqual({ ok: true, packages: packages.map((p) => ({ ...p, dependencies: [] })) });
  });
});

describe("cargoTomlPackageName", () => {
  it("[package]テーブルのnameを読む(他のテーブルのnameは読まない)", () => {
    expect(cargoTomlPackageName(`[lib]\nname = "other"\n\n[package] # c\nedition = "2021"\nname = "app" # c\n`)).toBe("app");
  });

  it.each([
    ["[package]が無い(virtual manifest)", `[workspace]\nmembers = ["a"]\n`],
    ["nameが文字列でない", `[package]\nname.workspace = true\n`],
    ["リテラル文字列", `[package]\nname = 'app'\n`],
    ["crate名として不正", `[package]\nname = "a b"\n`],
  ])("読めない場合はnull(%s)", (_label, text) => {
    expect(cargoTomlPackageName(text)).toBeNull();
  });
});

describe("[replace]の解決(レビュー指摘: 置換元のcrates.ioのcrateをスキャンしない)", () => {
  /** cargo 1.98(generate-lockfile --offline)が`[replace] "anyhow:1.0.102" = { path = "fake" }`で生成した内容 */
  const REPLACED_BY_PATH = `version = 4

[[package]]
name = "adler2"
version = "2.0.1"
source = "${CRATES_IO}"
checksum = "320119579fcad9c21884f5c4861d16174d0e06250625266f50fe6898340abefa"

[[package]]
name = "anyhow"
version = "1.0.102"

[[package]]
name = "anyhow"
version = "1.0.102"
source = "${CRATES_IO}"
checksum = "7f202df86484c868dbad7eaa557ef785d5c66295e41b460ef922eca0723b842c"
replace = "anyhow 1.0.102"

[[package]]
name = "rep"
version = "0.1.0"
dependencies = [
 "adler2",
 "anyhow 1.0.102 (${CRATES_IO})",
]
`;

  it("pathへの置換: 置換元(crates.io)はスキャンせず、置換先はローカルのcrateとして数える", () => {
    const parsed = parseCargoLock(REPLACED_BY_PATH);
    if (!parsed.ok) throw new Error(parsed.reason);
    expect(parsed.packages[2]!.replace).toBe("anyhow 1.0.102");
    const classified = classifyCargoPackages(parsed.packages);
    expect(classified.cratesIo.map((p) => p.name)).toEqual(["adler2"]);
    expect(classified.localCrates).toEqual(["anyhow", "rep"]);
    expect(cargoLockCopyContent(classified.cratesIo)).not.toContain("anyhow");
  });

  it("gitへの置換: 置換先はgitの依存としてスキャンしない", () => {
    const git = "git+https://github.com/me/anyhow?branch=fix#0123456789abcdef";
    const text = `version = 4

[[package]]
name = "anyhow"
version = "1.0.102"
source = "${CRATES_IO}"
replace = "anyhow 1.0.102 (${git})"

[[package]]
name = "anyhow"
version = "1.0.102"
source = "${git}"
`;
    const parsed = parseCargoLock(text);
    if (!parsed.ok) throw new Error(parsed.reason);
    const classified = classifyCargoPackages(parsed.packages);
    expect(classified.cratesIo).toEqual([]);
    expect(classified.unscannable).toEqual([{ name: "anyhow", version: "1.0.102", kind: "git" }]);
  });

  it.each([
    ["置換先の記載が無い", `replace = "anyhow 1.0.102 (git+https://x#abc)"`],
    ["置換先のIDを解釈できない", `replace = "anyhow"`],
    ["自分自身を指す", `replace = "anyhow 1.0.102 (${CRATES_IO})"`],
  ])("置換先を確かめられなければファイル全体を除外する(%s)", (_label, replaceLine) => {
    const result = parseCargoLock(`[[package]]\nname = "anyhow"\nversion = "1.0.102"\nsource = "${CRATES_IO}"\n${replaceLine}\n`);
    expect(result).toEqual({ ok: false, reason: expect.stringContaining("the replacement of anyhow 1.0.102 by [replace] was not found") });
  });

  it("parsePackageId", () => {
    expect(parsePackageId("a 1.0.0")).toEqual({ name: "a", version: "1.0.0", source: null });
    expect(parsePackageId(`a 1.0.0 (${CRATES_IO})`)).toEqual({ name: "a", version: "1.0.0", source: CRATES_IO });
    expect(parsePackageId("a")).toBeNull();
  });
});

describe("cargoWorkspace / workspaceIncludes(レビュー指摘: 名前だけで所属を確定しない)", () => {
  /** cargo 1.98で確認したworkspace: lockfileに収録されたのはca・cb・cinner・tt1(crates/exは除外、otherは非メンバー) */
  const ROOT = `[workspace]
members = [
  "crates/*", # glob
  "./crates/ex/inner/",
  "tools/t?",
]
exclude = ["crates/ex"]
resolver = "2"
`;

  it("membersとexcludeを複数行・コメント・末尾カンマ付きで読む", () => {
    expect(cargoWorkspace(ROOT)).toEqual({ members: ["crates/*", "./crates/ex/inner/", "tools/t?"], exclude: ["crates/ex"] });
  });

  it.each([
    ["crates/a", true],
    ["crates/b", true],
    ["crates/ex", false], // globで一致してもexcludeで除かれる
    ["crates/ex/inner", true], // 文字どおり書かれたメンバーはexcludeより優先
    ["tools/t1", true],
    ["tools/t10", false],
    ["other", false],
    ["crates/a/nested", false],
  ])("cargoの実際の挙動と同じ判定: %s → %s", (dir, expected) => {
    expect(workspaceIncludes(cargoWorkspace(ROOT)!, dir)).toBe(expected);
  });

  it.each([
    ["**のglob", { members: ["crates/**"], exclude: [] }, "crates/a"],
    ["文字クラスのglob", { members: ["crates/[ab]"], exclude: [] }, "crates/a"],
    ["ルートの外を指すメンバー", { members: ["../x"], exclude: [] }, "crates/a"],
    ["解釈できないexclude", { members: ["crates/*"], exclude: ["/abs"] }, "crates/a"],
  ])("判定できない場合はnull(%s)", (_label, workspace, dir) => {
    expect(workspaceIncludes(workspace, dir)).toBeNull();
  });

  it.each([
    ["[workspace]が無い", `[package]\nname = "app"\n`],
    ["membersが文字列の配列でない", `[workspace]\nmembers = ['a']\n`],
    ["閉じない配列", `[workspace]\nmembers = ["a",\n`],
  ])("cargoWorkspaceはnull(%s)", (_label, text) => {
    expect(cargoWorkspace(text)).toBeNull();
  });
});

describe("Cargo.tomlの複数行文字列(レビュー指摘: 文字列内の記述を設定と誤認しない)", () => {
  /** レビューで示された例: 説明文の中にworkspaceの設定に見える記述がある有効なCargo.toml */
  const DESCRIPTION_LOOKS_LIKE_WORKSPACE = `[package]
name = "app"
version = "0.1.0"
description = """
[workspace]
members = ["sub"]
"""
`;

  it.each([
    ["レビューの例", DESCRIPTION_LOOKS_LIKE_WORKSPACE],
    // 閉じの引用符がmembersの行末にあり、行ごとの判定では引用符で始まる行が現れない形
    ["閉じの引用符が同じ行にある", `[package]\nname = "app"\ndescription = """\n[workspace]\nmembers = ["sub"]"""\n`],
  ])("複数行の基本文字列の中の[workspace]はworkspaceとみなさない(%s)", (_label, text) => {
    expect(cargoWorkspace(text)).toBeNull();
    expect(cargoTomlPackageName(text)).toBe("app");
  });

  it("複数行のリテラル文字列の中の[package]・nameは読まない", () => {
    const text = `[workspace.metadata]\ndoc = \'\'\'\n[package]\nname = "fake"\n\'\'\'\n\n[package]\nname = "real"\n`;
    expect(cargoTomlPackageName(text)).toBe("real");
  });

  it("文字列の後に本物のworkspaceがあれば読む(閉じの引用符の直前の引用符・文字列内の括弧・#を含む)", () => {
    const text = `[package]
name = "app"
description = """x [workspace] ""\\""""
readme = "a ] # b"
license = 'MIT # [x]'

[workspace]
members = ["crates/*"] # c
`;
    expect(cargoWorkspace(text)).toEqual({ members: ["crates/*"], exclude: [] });
    expect(cargoTomlPackageName(text)).toBe("app");
  });

  it("複数行の配列の中の見出しに見える行も見出しとみなさない", () => {
    const text = `[workspace]\nmembers = [\n  "a",\n]\nexclude = [\n  "b",\n]\n`;
    expect(cargoWorkspace(text)).toEqual({ members: ["a"], exclude: ["b"] });
    expect(topLevelTomlLines(`a = [\n"[workspace]",\n]\n`)!.map((l) => l.line)).toEqual(["a = [", ""]);
  });

  it.each([
    ["閉じない複数行文字列", `[package]\nname = "app"\ndescription = """\n[workspace]\nmembers = ["sub"]\n`],
    ["閉じない文字列", `[package]\nname = "app\n[workspace]\nmembers = ["sub"]\n`],
    ["括弧の不整合", `[workspace]\nmembers = ["a"]]\n`],
  ])("解釈できない場合はnull(%s)", (_label, text) => {
    expect(topLevelTomlLines(text)).toBeNull();
    expect(cargoWorkspace(text)).toBeNull();
    expect(cargoTomlPackageName(text)).toBeNull();
  });

  it.each([
    ["引用符付きのキー", `[workspace]\nmembers = ["*"]\n"exclude" = ["sub"]\n`],
    ["ルートのテーブルのドット付きのキー", `workspace.exclude = ["sub"]\n[workspace]\nmembers = ["*"]\n`],
    ["配列の中の複数行文字列", `[workspace]\nmembers = ["""a"""]\n`],
  ])("読み落としの可能性がある書き方はnull(%s)", (_label, text) => {
    expect(cargoWorkspace(text)).toBeNull();
  });
});
