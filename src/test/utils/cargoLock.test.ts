describe("parseCargoLock", () => {
  it("v3形式: パッケージのname・version・source・依存を読み、[[patch.unused]]は無視する", () => {
    const result = parseCargoLock(V3);
    expect(result.ok).toBe(true);
    if (!result.ok) return;
    expect(result.packages.map((p) => `${p.name}@${p.version}`)).toEqual([
      "app@0.1.0", "failure@0.1.8", "gitdep@0.3.0", "mylib@0.2.0", "private@1.0.0", "smallvec@0.6.9", "smallvec@1.6.0",
    ]);
    expect(result.packages[0]).toEqual({ name: "app", version: "0.1.0", source: null, dependencies: ["failure", "mylib", "smallvec 1.6.0"] });
    expect(result.packages[1]!.source).toBe(CRATES_IO);
  });

  it("v4形式・CRLF・BOM・1行の依存配列・末尾のコメントを読む", () => {
    const text = `﻿version = 4\r\n\r\n[[package]] # c\r\nname = "a"\r\nversion = "1.0.0" # c\r\nsource = "${CRATES_IO}"\r\ndependencies = ["b", "c 1.0.0"]\r\n`;
    const result = parseCargoLock(text);
    expect(result).toEqual({ ok: true, packages: [{ name: "a", version: "1.0.0", source: CRATES_IO, dependencies: ["b", "c 1.0.0"] }] });
  });

  it("v1形式: 先頭のversionが無く、依存は`名前 版 (source)`、[metadata]のchecksumを読み飛ばす", () => {
    const text = `[[package]]
name = "app"
version = "0.1.0"
dependencies = [
 "smallvec 1.6.0 (${CRATES_IO})",
]

[[package]]
name = "smallvec"
version = "1.6.0"
source = "${CRATES_IO}"

[metadata]
"checksum smallvec 1.6.0 (${CRATES_IO})" = "1a55ca5f3b68e41c979bf8c46a6f1da892ca4db8f94023ce0bd32407573b1ac0"
`;
    const result = parseCargoLock(text);
    expect(result.ok && result.packages.map((p) => [p.name, p.dependencies])).toEqual([
      ["app", [`smallvec 1.6.0 (${CRATES_IO})`]],
      ["smallvec", []],
    ]);
  });

  it("文字列のエスケープを解釈する", () => {
    const result = parseCargoLock(`[[package]]\nname = "a\\u0062"\nversion = "1.0.0"\nsource = "x\\"y\\\\z"\n`);
    expect(result.ok && result.packages[0]).toEqual({ name: "ab", version: "1.0.0", source: 'x"y\\z', dependencies: [] });
  });

  it.each([
    ["想定外のテーブル", `[[package]]\nname = "a"\nversion = "1"\n[package.metadata]\n`],
    ["インラインテーブル", `[[package]]\nname = "a"\nversion = "1"\nsource = { git = "x" }\n`],
    ["リテラル文字列", `[[package]]\nname = 'a'\nversion = "1"\n`],
    ["複数行文字列", `[[package]]\nname = """a"""\nversion = "1"\n`],
    ["ドット付きのキー", `[[package]]\nname = "a"\nversion = "1"\nsource.git = "x"\n`],
    ["nameの重複", `[[package]]\nname = "a"\nname = "b"\nversion = "1"\n`],
    ["versionの欠落", `[[package]]\nname = "a"\n`],
    ["テーブルの後の先頭のversion", `[[package]]\nname = "a"\nversion = "1"\n[metadata]\nversion = 3\n`],
    ["先頭の他のキー", `foo = "x"\n[[package]]\nname = "a"\nversion = "1"\n`],
    ["閉じない依存配列", `[[package]]\nname = "a"\nversion = "1"\ndependencies = [\n "b",\n`],
    ["依存配列の想定外の要素", `[[package]]\nname = "a"\nversion = "1"\ndependencies = [\n b,\n]\n`],
    ["不正なエスケープ", `[[package]]\nname = "a\\q"\nversion = "1"\n`],
    ["サロゲートのエスケープ", `[[package]]\nname = "a\\uD800"\nversion = "1"\n`],
    ["値の後ろの余分な内容", `[[package]]\nname = "a" "b"\nversion = "1"\n`],
    ["crate名として不正な文字", `[[package]]\nname = "../x"\nversion = "1"\n`],
    ["版として不正な文字", `[[package]]\nname = "a"\nversion = "1 2"\n`],
    ["古い[root]テーブル", `[root]\nname = "a"\nversion = "1"\n`],
  ])("想定外の内容(%s)はファイル全体を失敗にし、行番号を示す", (_label, text) => {
    const result = parseCargoLock(text);
    expect(result.ok).toBe(false);
    if (!result.ok) expect(result.reason).toMatch(/^Cargo\.lock could not be interpreted with certainty \(.+ at line \d+\), so the file was excluded from the scan$/);
  });

  it("空のファイルはパッケージ0件", () => {
    expect(parseCargoLock("")).toEqual({ ok: true, packages: [] });
  });
});

describe("classifyCargoPackages", () => {
  it("crates.io由来だけをスキャン対象にし、ローカル・git・別レジストリを分ける", () => {
    const result = parseCargoLock(V3);
    if (!result.ok) throw new Error(result.reason);
    const classified = classifyCargoPackages(result.packages);
    expect(classified.cratesIo.map((p) => `${p.name}@${p.version}`)).toEqual(["failure@0.1.8", "smallvec@0.6.9", "smallvec@1.6.0"]);
    expect(classified.localCrates).toEqual(["app", "mylib"]);
    expect(classified.unscannable).toEqual([
      { name: "gitdep", version: "0.3.0", kind: "git" },
      { name: "private", version: "1.0.0", kind: "registry" },
    ]);
  });

  it("name・version・sourceが同じパッケージの重複は1つにまとめる", () => {
    const pkg = { name: "a", version: "1.0.0", source: CRATES_IO, dependencies: [] };
    expect(classifyCargoPackages([pkg, { ...pkg }]).cratesIo).toHaveLength(1);
  });

  it.each([
    [null, "local"],
    [CRATES_IO, "crates_io"],
    [SPARSE, "crates_io"],
    ["sparse+https://index.crates.io", "registry"], // 末尾の/が無いものはcrates.ioと断定しない
    ["registry+https://github.com/rust-lang/crates.io-index.git", "registry"],
    ["git+https://github.com/rust-lang/crates.io-index", "git"],
    ["path+file:///x", "registry"],
  ])("cargoSourceKind(%s) = %s", (source, kind) => {
    expect(cargoSourceKind(source)).toBe(kind);
  });
});

