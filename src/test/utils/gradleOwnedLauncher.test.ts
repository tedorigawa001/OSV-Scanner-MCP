import { createHash } from 'node:crypto';
import { execFileSync } from 'node:child_process';
import { mkdtempSync, readFileSync, rmSync, writeFileSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { expect, it } from 'vitest';
const fixture=fileURLToPath(new URL('../fixtures/q2b/build_fixture.py',import.meta.url));
it('generates offline VM units with manager-owned passcred listeners and a closed startup plan',()=>{
 const dir=mkdtempSync(join(tmpdir(),'q2b-units-'));
 try {
  execFileSync('python3',['-I',fixture,dir],{encoding:'utf8',timeout:10000});
  const root=join(dir,'rootfs');
  const socket=readFileSync(join(root,'etc/systemd/system/osv-q2b-reader.socket'),'utf8');
  expect(socket).toContain('PassCredentials=yes');expect(socket).toContain('SocketUser=root');expect(socket).toContain('Accept=no');
  const service=readFileSync(join(root,'etc/systemd/system/osv-q2b-b1b.service'),'utf8');
  expect(service).toContain('User=root');expect(service).toContain('Restart=no');
  expect(service).toContain('UnsetEnvironment=');expect(service).not.toContain('EnvironmentFile=');
  expect(JSON.parse(readFileSync(join(dir,'bundle.json'),'utf8')).nativeIsolationVerified).toBe(false);
 }finally{rmSync(dir,{recursive:true,force:true});}
});

it.each(['reader','upload','publish'])('protects the %s endpoint with a pre-bind guard and no directory write delegation',role=>{
 const dir=mkdtempSync(join(tmpdir(),'q2b-role-'));
 try{
  execFileSync('python3',['-I',fixture,dir],{encoding:'utf8',timeout:10000});
  const unit=readFileSync(join(dir,'rootfs/etc/systemd/system/osv-q2b-'+role+'.socket'),'utf8');
  expect(unit).toContain('ExecStartPre=/opt/osv-q2b/b1b/launcher --prepare '+role);
  expect(unit).toContain('StandardInput=null');expect(unit).toContain('StandardOutput=journal');expect(unit).toContain('StandardError=journal');
  expect(unit).toContain('DirectoryMode=0755');expect(unit).toContain('RemoveOnStop=no');
  expect(unit).toContain('SocketGroup='+({reader:1202,upload:1203,publish:1204} as Record<string,number>)[role]);
  expect(unit).not.toContain('ExecStopPost=');
 }finally{rmSync(dir,{recursive:true,force:true});}
});
it('refuses a nonempty destination instead of overwriting an existing bundle',()=>{
 const dir=mkdtempSync(join(tmpdir(),'q2b-existing-'));
 try{
  writeFileSync(join(dir,'existing'),'keep');
  expect(()=>execFileSync('python3',['-I',fixture,dir],{stdio:'pipe',timeout:10000})).toThrow();
  expect(readFileSync(join(dir,'existing'),'utf8')).toBe('keep');
 }finally{rmSync(dir,{recursive:true,force:true});}
});
it('pins generated bytes, source hashes and production-disabled flags in the offline bundle',()=>{
 const dir=mkdtempSync(join(tmpdir(),'q2b-inventory-'));
 try{
  execFileSync('python3',['-I',fixture,dir],{encoding:'utf8',timeout:10000});
  const bundle=JSON.parse(readFileSync(join(dir,'bundle.json'),'utf8'));
  expect(bundle.compiled).toBe(false);expect(bundle.backendEligible).toBe(false);expect(bundle.profileApproved).toBe(false);
  expect(new Set(bundle.files.map((x:{path:string})=>x.path)).size).toBe(bundle.files.length);
  for(const file of bundle.files){const b=readFileSync(join(dir,'rootfs',file.path));expect(file.size).toBe(b.length);expect(file.sha256).toBe(createHash('sha256').update(b).digest('hex'));}
  const unit=readFileSync(join(dir,'rootfs/etc/systemd/system/osv-q2b-b1b.service'),'utf8');
  expect(unit).toContain('NoNewPrivileges=yes');expect(unit).toContain('CapabilityBoundingSet=CAP_SETUID CAP_SETGID CAP_SETPCAP');
 }finally{rmSync(dir,{recursive:true,force:true});}
});

const record=JSON.parse(readFileSync(new URL('../../../docs/validation/gradle-q2b-b1b-startup-2026-11-03.json',import.meta.url),'utf8'));
const plan=['honest','permuted','NODE_OPTIONS','PYTHONPATH','PYTHONHOME','LD_PRELOAD','LD_LIBRARY_PATH','PATH',
 'wrong-argv','wrong-pid','wrong-count','wrong-names','missing-fd','extra-fd','no-passcred','wrong-group','nonlistener',
 'duplicate-listener','writable-entry','symlink-entry','changed-entry','changed-runtime','writable-ancestor','wrong-root-mode','wrong-root-owner',
 'image-acl','socket-acl','stdin-file','stdout-file','stderr-file','stdin-null-rw','stdin-pipe','stdout-pipe','stderr-pipe',
 'stdout-named-peer','stderr-named-peer','stdout-untrusted-peer','stderr-untrusted-peer',
 ...['opt','run','var'].flatMap(base=>['symlink','dangling','regular','writable'].map(kind=>'path-'+base+'-'+kind)),
 ...['opt','run','var'].map(base=>'path-final-'+base),'path-existing-mode','stdio-witness-control','prepare-reader','prepare-upload','prepare-publish'];
it.each(plan)('records the native startup control %s without promoting it to isolation approval',name=>{
 const matches=record.cases.filter((c:{case:string})=>c.case===name);expect(matches).toHaveLength(1);
 const result=matches[0];expect(result.verified).toBe(true);
 if(name==='honest'||name==='permuted'){
  expect(result.outcome).toBe('startup-observed');expect(result.observation.uid).toEqual([1101,1101,1101]);
  expect(result.observation.gid).toEqual([1201,1201,1201]);expect(result.observation.bootstrapSeals).toBe(15);
  expect(result.observation.capabilitiesEmpty).toBe(true);expect(result.observation.nativeIsolationVerified).toBe(false);
 }else if(name==='stdio-witness-control'){
  expect(result.outcome).toBe('entrypoint-witness-observed');expect(result.runtimeEntrypointExecutions).toBe(1);
 }else if(name.startsWith('path-')){
  if(name==='path-existing-mode')expect(result.outcome).toBe('existing-parent-mode-preserved');
  else {expect(result.outcome).toBe('path-rejected-without-mutation');expect(result.outsideWrites).toBe(0);expect(result.outsideModeChanges).toBe(0);}
 }else if(name.startsWith('stdin-')||name.startsWith('stdout-')||name.startsWith('stderr-')){
  expect(result.outcome).toBe('stdio-rejected-silently');expect(result.protectedCanaryUnchanged).toBe(true);expect(result.runtimeEntrypointExecutions).toBe(0);
 }else if(name.startsWith('prepare-'))expect(result.outcome).toBe('absent-accepted-existing-rejected');
 else {expect(result.outcome).toBe('manager-rejected');expect(result.reason).toEqual(expect.any(String));}
});
it('binds native records to current source bytes, exact case closure, static ELF and the actual unit verifier',()=>{
 expect(record.verifiedCases).toBe(plan.length);expect(record.cases).toHaveLength(plan.length);
 expect(new Set(record.cases.map((c:{case:string})=>c.case)).size).toBe(plan.length);
 for(const source of record.sources){
  const path=new URL('../fixtures/q2b/'+source.path,import.meta.url);
  expect(source.sha256).toBe(createHash('sha256').update(readFileSync(path)).digest('hex'));
 }
 expect(record.sources.map((s:{path:string})=>s.path).sort()).toEqual(['README.md','build_fixture.py','launcher.c','native_probe.py','provider.py']);
 expect(record.stdioWitnessArtifacts.launcher).toMatch(/^[a-f0-9]{64}$/);expect(record.stdioWitnessArtifacts['provider.py']).toMatch(/^[a-f0-9]{64}$/);
 expect(record.launcherStaticElf).toBe(true);expect(record.launcherSha256).toMatch(/^[a-f0-9]{64}$/);
 expect(record.unitSyntaxValidation).toMatchObject({exitCode:0,stderr:'',unitCount:5});
 expect(record.systemdBootVerified).toBe(false);expect(record.nativeIsolationVerified).toBe(false);
 expect(record.profileApproved).toBe(false);expect(record.backendEligible).toBe(false);expect(record.originalReadsSkipped).toBe(0);
});
